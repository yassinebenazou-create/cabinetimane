function mergeItems(sourceItems, translatedItems) {
  if (!translatedItems) {
    return sourceItems
  }

  return sourceItems.map((item, index) => ({ ...item, ...translatedItems[index] }))
}

export function localizeService(service, language) {
  if (!service || language !== 'ar') {
    return service
  }

  const translation = arabicServices[service.slug]
  if (!translation) {
    return service
  }

  return {
    ...service,
    ...translation,
    steps: mergeItems(service.steps, translation.steps),
    benefits: mergeItems(service.benefits, translation.benefits),
  }
}

export function localizeServices(services, language) {
  return services.map((service) => localizeService(service, language))
}
